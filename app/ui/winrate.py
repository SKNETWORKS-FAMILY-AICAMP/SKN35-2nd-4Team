"""팀 전력 → 예상 승률 매핑.

원래 두 페이지에 `0.35 + overall * 0.003` 이라는 같은 스텁이 복붙돼 있었다
(simulation.py 가 승률 함수를 주입받도록 설계돼 있어서 화면이 임시로 채워둔 것).
그 상수는 실데이터와 맞춰본 적이 없어서 변동폭이 비현실적으로 작았다:

  구단 전력 범위 38.2~51.1 → 예상 승률 46.5%~50.3% (폭 3.9%p)
  같은 시즌 실제 승률                26.5%~59.9% (폭 33.4%p)

즉 실제 33.4%p 차이를 3.9%p 로 8.5배 압축해서, 어떤 선수를 빼도 승률이
거의 안 움직이는 것처럼 보였다.

여기 상수는 실제 데이터로 적합한 값이다 (2026-08-30 기준):
  - 표본: features_v1 로 계산한 팀 전력 + team_season.csv 의 실제 승률
          510개 팀-시즌 (2009~2025)
  - 상관: r = 0.576  (R² = 0.332)
  - 적합: win_rate = 0.1786 + 0.006704 * team_strength
  - 잔차 표준편차: 0.0626 (약 ±6.3%p)

주의 — 이 값의 한계를 화면에서 숨기지 말 것:
  전력은 승률 분산의 33%만 설명한다. 나머지 67%는 상대 전력, 불펜 운용,
  득실 분포, 운 등 이 지표에 없는 요인이다. 그래서 이 함수의 출력은
  "이 로스터면 대략 이 정도" 수준의 방향성이지 정확한 예측이 아니다.
  변화량(Δ)은 같은 함수로 계산한 두 값의 차이라 절대값보다 신뢰할 만하다.
"""

from __future__ import annotations

import numpy as np

# 실데이터 적합 계수 (위 docstring 의 회귀 결과)
WIN_RATE_INTERCEPT = 0.1786
WIN_RATE_SLOPE = 0.006704

# 적합 구간을 크게 벗어난 외삽을 막는 안전 범위. 2009~2025 실제 승률의
# 관측 범위(25.3%~71.7%)보다 살짝 넉넉하게 잡았다.
WIN_RATE_FLOOR = 0.20
WIN_RATE_CEIL = 0.75

# 전력이 승률 분산에서 차지하는 몫 — 화면에서 한계를 안내할 때 쓴다
WIN_RATE_R2 = 0.332
WIN_RATE_RESIDUAL_SD = 0.0626


def predict_win_rate_from_strength(overall: float) -> float:
    """팀 전력(0~100 가중평균) → 예상 승률(0~1)."""
    return float(
        np.clip(
            WIN_RATE_INTERCEPT + float(overall) * WIN_RATE_SLOPE,
            WIN_RATE_FLOOR,
            WIN_RATE_CEIL,
        )
    )


def win_rate_caption() -> str:
    """화면 하단에 붙일 한계 안내 문구."""
    return (
        f"승률은 팀 전력(출전비중 가중평균)으로 추정합니다 — 2009~2025 실제 "
        f"승률 510개 팀·시즌으로 적합했고, 전력이 승률 분산의 "
        f"{WIN_RATE_R2:.0%}만 설명합니다(잔차 ±{WIN_RATE_RESIDUAL_SD * 100:.1f}%p). "
        "절대값보다 이탈 전후 변화량을 보세요."
    )
